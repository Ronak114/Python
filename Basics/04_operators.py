a = 32
b = 2

# Arithmetic Operator
print("a + b = ", a + b)
print("a - b = ", a - b)
print("a * b = ", a * b)
print("a / b = ", a / b)
print("a % b = ", a % b)
print("a // b = ", a // b)
print("a ** b = ", a**b)

# Relational/Conditional Operators
print(a > 4)
print(a < 4)
print(a <= 4)
print(a >= 4)
print(a == 4)  # Is a equal to 4?
print(a == 32)  # Is a equal to 32?
print(a != 32)  # Is a not equal to 32?

