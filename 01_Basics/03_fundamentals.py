# COMMENTS

'''
comments are used to explain code and are ignored by the Python
interpreter.
Single-line comments start with # .
Multi-line comments are enclosed in  or """ or

Escape Sequences
Escape sequences are used to include special characters in strings.
Common escape sequences:
\n : Newline
\t : Tab
\\ : single Backslash
\" : Double quote
\' : Single quote
'''

## ESCAPE
print("Hey how are you\nI am good \\ ronak")
print('Hello " World')

# PRINT
print("Hello World", "Ronak", 14, sep=",")
print("Hello World", end="..")
print("ronak", end="//")
